class GetGradients:
    """Class used to read the QM gradients from Newton-X MD trajectories.

    This class does not require arguments in its constructor. The outputs generate by
    the class is given in eV/angstrom.

    Data attributes:
    ----------------
       ``trajectories`` (list): trajectories ID (TRAJXX) available in the working directory.\n
       ``all_grads`` (dict): store the gradient matrices (per state) for all MD trajectories.\n
       ``dataset`` (dict): dictionary of dataframes with the flattened gradient matrices.
    """

    # Defining slots to optimize memory access performance (RAM):
    __slots__ = ["trajectories", "all_grads", "datasets"]

    def __str__(self) -> str:
        """Provide a string representation of the class.

        :return: Short description of the class functionality.
        :rtype: str
        """
        return "Data loader object for QM gradients."

    def __init__(self) -> None:
        """Class initializer."""
        # This variable contains a list of all available trajectories:
        # [TRAJ1, TRAJ2,..., TRAJN]
        self.trajectories = check_nx_trajs()
        # Store the gradient matrices per state as a dictionary, where
        # the key is the state identifier (e.g., {'S1': np.array})
        self.all_grads = dict()
        self.datasets = dict()

    @staticmethod
    def from_h5(outfile) -> dict:
        """Read XYZ gradients from a single trajectory generated by the new Newton-X.

        :param outfile: name of the NX output file in the .h5 format, usually dyn.h5.
        :type outfile: str
        :return: stacked XYZ gradients for all steps of a single MD trajectory, returned as
                 as a dictionary of tensors (numpy.ndarray, one for each state) with shape
                 (n_steps, n_atoms, 3).
        :rtype: dict
        """
        grads_dict = dict()
        data = h5py.File(outfile, "r")
        path_to_grads = "particles/all/gradients/value"
        xyz_grads = np.array(data[path_to_grads], dtype=np.float64)
        n_states = xyz_grads.shape[-1]

        for state in range(n_states):
            grads_dict[state] = xyz_grads[:, :, :, state]

        return grads_dict

    @staticmethod
    def from_nxlog(outfile, tmax=100000) -> dict:
        """Read XYZ gradients from one trajectory generated by the old Newton-X.

        This method has the same parameters and return type as in :meth:`~ulamdyn.GetGradients.from_h5`.

        :param outfile: Output file from Newton-X MD trajectory, namely nx.log.
        :type outfile: str
        :return: dictionary of numpy.ndarray with shape (n_steps, n_atoms, 3), where the keys
                 correspond to the state's id.
        :rtype: dict
        """
        read_grads = False
        count_start = 0
        t_current = 0
        t_hop = np.inf

        grads_dict = dict()

        with open(outfile, "r") as nx_log:
            for line in nx_log:

                # This condition is used to monitor the MD restarting, and
                # then skip the repeated gradients (Step 0 of each restart)
                if "STARTING MOLECULAR DYNAMICS" in line:
                    count_start += 1

                if "Nat" in line:
                    num_atoms = np.int(line.split()[-1])

                if "STEP" in line:
                    line_list = line.replace(",", "").split()
                    t_current = np.float(line_list[4])
                    if t_current == tmax:
                        break

                if "Time of hopping" in line:
                    t_hop = np.float(line.split()[-2])

                # The second condition in the if statement is used to skip
                # the gradients recalculated after hopping
                if ("Gradient" in line) and (t_current != t_hop):
                    if "current" in line:
                        continue
                    elif "state" in line:
                        state = "S" + line.split()[-2]
                    else:
                        state = "current_state"

                    if count_start == 2:
                        read_grads = False
                        count_start -= 1
                    else:
                        read_grads = True

                    if state not in grads_dict:
                        grads_dict[state] = list()
                    continue

                if read_grads:
                    vals = line.split()
                    if len(vals) == 3:
                        grads = np.array(vals, dtype=np.float64)
                        grads_dict[state].append(grads)
                    else:
                        read_grads = False

        for k in grads_dict.keys():
            grads_dict[k] = np.array(grads_dict[k])
            grads_dict[k] = grads_dict[k].reshape(-1, num_atoms, 3)
            grads_dict[k] *= HARTREE_TO_eV / BOHR_TO_ANG

        return grads_dict

    def read_all_trajs(self) -> None:
        """Read gradients from all MD trajectories and store into a dictionary."""
        all_grads = dict()
        for trj in self.trajectories:
            print("Reading gradients from %s" % trj + "...")
            tmax = self.trajectories.get(trj)
            files = os.listdir(trj + "/RESULTS")
            h5file = next((f for f in files if f.endswith(".h5")), None)
            if h5file:
                h5file = trj + "/RESULTS/" + h5file
                gradients = self.from_h5(h5file)
            elif os.path.isfile(trj + "/RESULTS/nx.log"):
                nxfile = trj + "/RESULTS/nx.log"
                gradients = self.from_nxlog(nxfile, tmax)
            else:
                print("\nOutput file nx.log or *.h5 not available.")
                print("Check the directory %s" % trj + "/RESULTS" + "\n")

            if not all_grads:
                all_grads = {key: list() for key in gradients.keys()}
            for k in all_grads.keys():
                all_grads[k].append(gradients[k])

        for k in all_grads.keys():
            self.all_grads[k] = np.concatenate(all_grads[k], axis=0)

    def build_dataframe(self, save_csv=False) -> None:
        """Generate a dataset (pandas.DataFrame object) with all gradients.

        The XYZ matrices with the gradients of each molecular geometry is flattened into a
        one dimensional vector, such that every row of the dataset corresponds to one step
        of the MD trajectories.

        :param save_csv: if True enable the output of all gradient dataframes in a csv format,
                         defaults to False. The default name of the outputed dataset is
                         all_gradients_s[n].csv, where *n* is the number of the state.
        :type save_csv: bool, optional
        """
        if not self.all_grads:
            self.read_all_trajs()

        state = list(self.all_grads.keys())[0]
        n_atoms = self.all_grads[state].shape[1]
        col_names = [
            ["Gx" + str(i), "Gy" + str(i), "Gz" + str(i)] for i in range(1, n_atoms + 1)
        ]
        col_names = sum(col_names, [])

        for k in self.all_grads.keys():
            df = pd.DataFrame(
                self.all_grads[k].reshape(-1, n_atoms * 3), columns=col_names
            )
            self.datasets[k] = df
            if save_csv:
                output = "all_gradients_" + k.lower() + ".csv"
                df.to_csv(output, index=False, header=True)


