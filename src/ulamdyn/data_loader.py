#%% Starting the first class: GetCoords
class GetCoords:
    """Class used to read the Cartesian coordinates from Newton-X MD trajectories.

    .. note:: The Cartesian XYZ coordinates can be read either from dyn.out/dyn.xyz
              files generated by the classical NX or from the h5 file of NX new series.
              Repeated geometries will be skipped.

    It also provides a function to calculate the root-mean-squared deviation (RMSD)
    between each geometry read from the MD trajectories and a reference geometry.
    Before calculating the RMSD, the two geometries are aligned using the Kabsch algorithm
    (https://en.wikipedia.org/wiki/Kabsch_algorithm).

    This class does not require arguments in its constructor. All the outputs generate by
    the class are given in angstroms.

    Data attributes:
    ----------------
       ``trajectories`` (list): trajectories ID (TRAJXX) available in the working directory.\n
       ``labels`` (numpy.ndarray): stores the sequence of atom labels.\n
       ``eq_xyz`` (numpy.ndarray): stores the XYZ matrix of the reference geometry (geom.xyz).\n
       ``xyz`` (numpy.ndarray): stores the XYZ matrices of all geometries read from the TRAJ directories.\n
       ``rmsd`` (numpy.ndarray): vector of RMSD values between all geometries and the reference one.\n
       ``dataset`` (pandas.dataframe): stores a dataframe of the flattened XYZ matrices.
    """

    # Defining slots to optimize performance (RAM):
    __slots__ = [
        "trajectories",
        "labels",
        "eq_xyz",
        "xyz",
        "rmsd",
        "dataset",
        "traj_time",
    ]

    def __str__(self) -> str:
        """Provide a string representation of the class.

        :return: Short description of the class functionality.
        :rtype: str
        """
        return "Data loader object for molecular geometries."

    def __init__(self) -> None:
        """Class initialization."""
        # This variable contains a list of all available trajectories:
        # [TRAJ1, TRAJ2,..., TRAJN]
        self.trajectories = check_nx_trajs()

        # Store the sequence of atom labels as a numpy array
        self.labels = None
        # Store the XYZ matrix of the reference geometry (np.array)
        self.eq_xyz = None
        # Try to read the reference geometry, geom.xyz file
        # If the file is available, the labels and eq_xyz variables
        # will be update with the data loaded by the function below.
        self.read_eq_geom()

        self.xyz = None
        self.rmsd = None
        self.dataset = None
        self.traj_time = None

    @property
    def save_csv(self) -> None:
        """Save all loaded geometries (raw format) into a csv file.

        If the RMSD has been calculated, it will be included as an extra column in the
        XYZ coordinates data set.

        The default name of the output file is all_coordinates.csv.
        """
        if self.dataset is None:
            self.build_dataframe()

        df = self.dataset

        if self.rmsd is not None:
            df["RMSD"] = self.rmsd

        df.to_csv("all_coordinates.csv", index=False, header=True)

    def build_dataframe(self) -> None:
        """Create a pandas DataFrame containing the XYZ coordinates from all trajectories.

        After running this function, the class attribute :attr:`~ulamdyn.GetCoords.dataset` will
        be updated with the loaded DataFrame object.
        """
        if all(v is not None for v in [self.labels, self.xyz]):
            n_atoms = len(self.labels)
            col_names = [
                ["x" + str(i), "y" + str(i), "z" + str(i)]
                for i in range(1, n_atoms + 1)
            ]
            col_names = sum(col_names, [])
            df = pd.DataFrame(self.xyz.reshape(-1, n_atoms * 3), columns=col_names)

            if self.traj_time is not None:
                df.insert(0, "TRAJ", self.traj_time[:, 0])
                df.insert(1, "time", self.traj_time[:, 1])
                df["TRAJ"] = df["TRAJ"].astype(int)

            self.dataset = df

            print("                                                  ")
            print("------------------------------------------------  ")
            print("  The size of the XYZ coordinates data set is\n   ")
            print("     Number of geometries = {}".format(df.shape[0]))
            print("       Number of features = {}".format(df.shape[1]))
            print("------------------------------------------------  \n")

        else:
            print("---------------------------------------")
            print("The coordinates variable is empty!")
            print("There is no data available to save.")
            print("Please run the loader functions first.")
            print("---------------------------------------")

    @staticmethod
    def from_h5(outfile) -> Tuple[np.ndarray, np.ndarray]:
        """Read the XYZ coordinates from the .h5 file generated by the new Newton-X.

        :param outfile: name of the NX output file, usually dyn.h5
        :type outfile: str
        :return: tuple containing an array of strings defining the atom labels, and a
                 tensor of shape (n_steps, n_atoms, 3) with all XYZ coordinates of a
                 single MD trajectory.
        :rtype: tuple in the form (numpy.ndarray, numpy.ndarray)
        """
        data = h5py.File(outfile, "r")
        path_to_coords = "particles/all/position/value"
        xyz_geoms = np.array(data[path_to_coords], dtype=np.float64)
        path_to_labels = "particles/all/names"
        atom_labels = np.array(data[path_to_labels], dtype="U")

        return (atom_labels, xyz_geoms)

    def from_dyn(self, outfile, tmax=100000) -> Tuple[np.ndarray, np.ndarray]:
        """Get XYZ coordinates from the dyn.out file of classical Newton-X.

        :param outfile: name of the NX output file, dyn.out
        :type outfile: str
        :return: tuple containing an array of strings defining the atom labels, and a
                 tensor of size (n_steps, n_atoms, 3) with all XYZ coordinates of a
                 single MD trajectory.
        :rtype: tuple in the form (numpy.ndarray, numpy.ndarray)
        """
        read_coords = False
        t = -1
        current_time = -1
        num_atoms = np.inf
        t_list = []

        xyz_geoms = list()
        append_geoms = xyz_geoms.append
        atom_labels = list()
        counter = 0

        if self.labels is not None:
            num_atoms = len(self.labels)
            atom_labels = self.labels

        with open(outfile, "r") as dyn_out:
            for line in dyn_out:

                # By keeping track of the current time we can deal with
                # repetitions in restart calculations, but also to deal
                # with switching in QM/MM dynamics.
                if "TIME" in line:
                    current_time = np.float(line.split()[-2])
                    if current_time > tmax:
                        break

                if read_coords:
                    vals = line.split()
                    if len(vals) == 6:
                        counter += 1
                        if counter > num_atoms:
                            counter = 0
                            read_coords = False
                            continue
                        coords = np.array(vals[2:5], dtype=np.float64)
                        # xyz_geoms.append(coords)
                        append_geoms(coords)
                        # Labels will be read only in the first iteration
                        if current_time == 0.0 and isinstance(atom_labels, list):
                            atom_labels.append(vals[0].upper())
                    else:
                        t_list.append(current_time)
                        read_coords = False
                        counter = 0

                # This condition is used to skip repeated geometries.
                if "geometry" in line:
                    if current_time == t:
                        read_coords = False
                    else:
                        read_coords = True
                    t = current_time

        num_atoms = len(atom_labels)

        xyz_geoms = np.array(xyz_geoms)
        xyz_geoms = xyz_geoms.reshape(-1, num_atoms, 3)
        xyz_geoms *= BOHR_TO_ANG
        atom_labels = np.asarray(atom_labels)
        t_list = np.asarray(t_list)

        return (atom_labels, xyz_geoms, t_list)

    @staticmethod
    def from_xyz(xyzfile) -> Tuple[np.ndarray, np.ndarray]:
        """Get XYZ coordinates from the dyn.xyz file of classical Newton-X.

        This method has the same parameters and return type as in :meth:`~ulamdyn.GetCoords.from_dyn`.
        """
        count = 0
        xyz_geoms = list()
        atom_labels = list()

        with open(xyzfile, "r") as inp:
            for line in inp:
                vals = line.split()

                if len(vals) == 1 and count == 0:
                    num_atoms = int(vals[0])

                if len(vals) >= 4:
                    coords = np.array(vals[-3:], dtype=np.float64)
                    coords = coords.reshape(-1, 3)
                    xyz_geoms.append(coords)
                    if count <= num_atoms + 2:
                        atom_labels.append(vals[0])

                count += 1

        atom_labels = np.asarray(atom_labels)
        xyz_array = np.vstack(xyz_geoms).reshape(-1, num_atoms, 3)

        return (atom_labels, xyz_array)

    def read_all_trajs(self) -> None:
        """Concatenate the XYZ coordinates read from all available MD trajectories.

        After running this method, the class attributes :attr:`~ulamdyn.GetCoords.labels`
        and :attr:`~ulamdyn.GetCoords.xyz` will be updated.
        """
        traj_id = list()
        t_vals = list()
        all_geoms = list()
        append_trajs = traj_id.append
        append_times = t_vals.append
        append_all_geoms = all_geoms.append
        for trj in self.trajectories:
            print("Reading geometries from %s" % trj + "...")
            tmax = self.trajectories.get(trj)
            results_dir = trj + "/RESULTS/"
            files = os.listdir(results_dir)
            h5file = next((f for f in files if f.endswith(".h5")), None)
            if h5file:
                h5file = results_dir + h5file
                atom_labels, xyz = self.from_h5(h5file)
                # all_geoms.append(xyz)
                append_all_geoms(xyz)
            elif os.path.isfile(results_dir + "dyn.out"):
                dynfile = results_dir + "dyn.out"
                atom_labels, xyz, t = self.from_dyn(dynfile, tmax)
                # all_geoms.append(xyz)
                append_all_geoms(xyz)
                append_times(t)
                n_steps = len(t)
                current_traj = np.int(trj.replace("TRAJ", ""))
                append_trajs(np.full(n_steps, current_traj, dtype=np.int))
            elif os.path.isfile(results_dir + "dyn.xyz"):
                xyzfile = results_dir + "dyn.xyz"
                atom_labels, xyz = self.from_xyz(xyzfile)
                # all_geoms.append(xyz)
                append_all_geoms(xyz)
            else:
                print("\nNX output file not found.")
                print("Check the directory %s" % trj + "/RESULTS" + "\n")

        t_vals = np.concatenate(t_vals)
        traj_id = np.concatenate(traj_id)
        self.traj_time = np.concatenate(
            [traj_id.reshape(-1, 1), t_vals.reshape(-1, 1)], axis=1
        )
        self.xyz = np.concatenate(all_geoms, axis=0)
        self.labels = atom_labels

    def read_eq_geom(self) -> None:
        """Read the XYZ coordinates of a reference geometry.

        .. note:: This method should be executed before calculating the RMSD with the
                  :meth:`~ulamdyn.GetCoords.align_geoms` function.

        A file with name geom.xyz must be provided in the working directory (TRAJECTORIES).
        After reading the coordinates, the method will update the class attributes
        :attr:`~ulamdyn.GetCoords.labels` and :attr:`~ulamdyn.GetCoords.eq_xyz`.
        """
        try:
            atom_labels, ref_geom = self.from_xyz("geom.xyz")
            self.eq_xyz = np.squeeze(ref_geom, axis=0)
            self.labels = atom_labels
        except FileNotFoundError:
            print("\n-----------------------------------------------------------")
            print("Reference geometry not found!")
            print("The reference geometry is required to compute the RMSD. ")
            print("Check if the geom.xyz file is available in the current dir.")
            print("-----------------------------------------------------------\n")

    @property
    def align_geoms(self) -> None:
        """Calculate the RMSD between the current and reference geometries.

        .. note:: Before calculating the RMSD, the method uses the Kabsch algorithm to find
                  the optimal alignment between the loaded molecular geometry for each time
                  step t and the reference geometry.

        The calculated RMSD values will be stored in the class attribute
        :attr:`~ulamdyn.GetCoords.rmsd_values`, while the :attr:`~ulamdyn.GetCoords.xyz`
        attribute will be updated with the aligned geometries.
        """
        if self.eq_xyz is None:
            self.read_eq_geom()

        self.eq_xyz -= rmsd.centroid(self.eq_xyz)

        if self.xyz is not None:
            xyz_dim = self.xyz.shape
            aligned_geoms = np.empty(xyz_dim, dtype=np.float64)
            rmsd_values = np.empty((xyz_dim[0]), dtype=np.float64)
        else:
            error_msg = "XYZ coordinates not loaded!" + "\n "
            error_msg += "Please make sure that the read_all_trajs function "
            error_msg += "has been executed." + "\n "
            print(error_msg)
            return

        for idx, geom in enumerate(self.xyz):
            geom -= rmsd.centroid(geom)
            U = rmsd.kabsch(geom, self.eq_xyz)
            geom = np.dot(geom, U)
            geom_rmsd = rmsd.rmsd(self.eq_xyz, geom)
            aligned_geoms[idx] = geom
            rmsd_values[idx] = geom_rmsd

        self.xyz = aligned_geoms
        self.rmsd = rmsd_values


