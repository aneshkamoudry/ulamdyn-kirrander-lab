#%% Starting the first class: GetCoords
class GetCoords:
    """Class used to read the Cartesian coordinates from Newton-X MD trajectories.

    .. note:: The Cartesian XYZ coordinates can be read either from dyn.out/dyn.xyz
              files generated by the classical NX or from the h5 file of new NX.
              Repeated geometries will be skipped.

    It also provides a function to calculate the root-mean-squared deviation (RMSD)
    between each geometry read from the MD trajectories and a reference geometry.
    Before calculating the RMSD, the two geometries are aligned using the Kabsch algorithm
    (https://en.wikipedia.org/wiki/Kabsch_algorithm).

    This class does not require arguments in its constructor. All the outputs generate by
    the class are given in angstroms.

    Data attributes:
    ----------------
       ``trajectories`` (list): trajectories ID (TRAJXX) available in the working directory.\n
       ``labels`` (np.ndarray): stores the sequence of atom labels.\n
       ``eq_xyz`` (np.ndarray): stores the XYZ matrix of the reference geometry (geom.xyz).\n
       ``xyz`` (np.ndarray): stores the XYZ matrices of all geometries read from the TRAJ directories.\n
       ``rmsd`` (np.ndarray): vector of RMSD values between all geometries and the reference one.\n
       ``dataset`` (pd.dataframe): stores a dataframe of the flattened XYZ matrices.

    """

    # Defining slots to optimize performance (RAM):
    __slots__ = ["trajectories", "labels", "eq_xyz", "xyz", "rmsd", "dataset"]

    def __str__(self):
        return "Data handler class for molecular geometries."

    def __init__(self):
        # This variable contains a list of all available trajectories:
        # [TRAJ1, TRAJ2,..., TRAJN]
        self.trajectories = get_traj_dirs()

        # Store the sequence of atom labels as a numpy array
        self.labels = None
        # Store the XYZ matrix of the reference geometry (np.array)
        self.eq_xyz = None
        # Try to read the reference geometry, geom.xyz file
        # If the file is available, the labels and eq_xyz variables
        # will be update with the data loaded by the function below.
        self.read_eq_geom()

        self.xyz = None
        self.rmsd = None
        self.dataset = None

    @property
    def save_csv(self):
        """Save all loaded geometries (raw format) as a csv file.

        If the RMSD has been calculated, it will be included as an extra column
        in the XYZ coordinates data set.
        """
        if self.dataset is None:
            self.build_dataframe()

        df = self.dataset

        if self.rmsd is not None:
            df["RMSD"] = self.rmsd

        df.to_csv("all_coordinates.csv", index=False, header=True)

    def build_dataframe(self):
        """Create a pandas DataFrame containing the XYZ coordinates from all trajectories.

        After running this function, the class attribute ``dataset`` will be updated with
        the loaded DataFrame object.
        """
        if all(v is not None for v in [self.labels, self.xyz]):
            n_atoms = len(self.labels)
            col_names = [
                ["x" + str(i), "y" + str(i), "z" + str(i)]
                for i in range(1, n_atoms + 1)
            ]
            col_names = sum(col_names, [])
            df = pd.DataFrame(self.xyz.reshape(-1, n_atoms * 3), columns=col_names)

            self.dataset = df

            print("                                                  ")
            print("------------------------------------------------  ")
            print("  The size of the XYZ coordinates data set is\n   ")
            print("     Number of geometries = {}".format(df.shape[0]))
            print("       Number of features = {}".format(df.shape[1]))
            print("------------------------------------------------  ")

        else:
            print("---------------------------------------")
            print("The coordinates variable is empty!")
            print("There is no data available to save.")
            print("Please run the loader functions first.")
            print("---------------------------------------")

    @staticmethod
    def from_h5(outfile):
        """Read the XYZ coordinates from the .h5 file generated by the new Newton-X.

        :param outfile: name of the NX output file, usually dyn.h5
        :type outfile: str
        :return: tuple containing the atom labels and a tensor of size (n_steps, n_atoms, 3)
                 with all XYZ coordinates of one trajectory.
        :rtype: tuple of numpy.arrays
        """
        data = h5py.File(outfile, "r")
        path_to_coords = "particles/all/position/value"
        xyz_geoms = np.array(data[path_to_coords], dtype=np.float64)
        path_to_labels = "particles/all/names"
        atom_labels = np.array(data[path_to_labels], dtype="U")

        return (atom_labels, xyz_geoms)

    def from_dyn(self, outfile):
        """Reads the coordinates from the dyn.out file of Newton-X.

        .. note:: The XYZ coordinates are given in Bohr, and will be converted
                  to Angstrom by the function.

        The number of coordinates to be read will be equal to the number of atoms
        existing in the reference geometry file, geom.xyz. In the case of QM/MM
        calculations, the coordinates of the solvent molecules will be ignored if
        the geom.xyz file contains only the geometry of the solute.

        Args:
           outfile (str): name of the NX output file, dyn.out.

        Returns:

        """
        read_coords = False
        t = -1
        current_time = -1
        num_atoms = np.inf

        xyz_geoms = list()
        atom_labels = list()
        counter = 0

        if self.labels is not None:
            num_atoms = len(self.labels)
            atom_labels = self.labels

        with open(outfile, "r") as dyn_out:
            for line in dyn_out:

                # By keeping track of the current time we can deal with
                # repetitions in restart calculations, but also to deal
                # with switching in QM/MM dynamics.
                if "TIME" in line:
                    current_time = np.float(line.split()[-2])

                if read_coords:
                    vals = line.split()
                    if len(vals) == 6:
                        counter += 1
                        if counter > num_atoms:
                            counter = 0
                            read_coords = False
                            continue
                        coords = np.array(vals[2:5], dtype=np.float64)
                        xyz_geoms.append(coords)
                        # Labels will be read only in the first iteration
                        if current_time == 0.0 and isinstance(atom_labels, list):
                            atom_labels.append(vals[0].upper())
                    else:
                        read_coords = False
                        counter = 0

                # This condition is used to skip repeated geometries.
                if "geometry" in line:
                    if current_time == t:
                        read_coords = False
                    else:
                        read_coords = True
                    t = current_time

        num_atoms = len(atom_labels)

        xyz_geoms = np.array(xyz_geoms)
        xyz_geoms = xyz_geoms.reshape(-1, num_atoms, 3)
        xyz_geoms *= BOHR_TO_ANG
        atom_labels = np.asarray(atom_labels)

        return (atom_labels, xyz_geoms)

    @staticmethod
    def from_xyz(xyzfile):
        """Read the coordinates from the dyn.xyz file of Newton-X."""
        count = 0
        xyz_geoms = list()
        atom_labels = list()

        with open(xyzfile, "r") as inp:
            for line in inp:
                vals = line.split()

                if len(vals) == 1 and count == 0:
                    num_atoms = int(vals[0])

                if len(vals) >= 4:
                    coords = np.array(vals[-3:], dtype=np.float64)
                    coords = coords.reshape(-1, 3)
                    xyz_geoms.append(coords)
                    if count <= num_atoms + 2:
                        atom_labels.append(vals[0])

                count += 1

        atom_labels = np.asarray(atom_labels)
        xyz_array = np.vstack(xyz_geoms).reshape(-1, num_atoms, 3)

        return (atom_labels, xyz_array)

    def read_all_trajs(self):
        """
        Load the XYZ coordinates from all available trajectories, and store the
        values in the class variable ``xyz`` as a numpy array.

        """

        all_geoms = list()
        for trj in self.trajectories:
            print("Reading geometries from %s" % trj + "...")
            results_dir = trj + "/RESULTS/"
            files = os.listdir(results_dir)
            h5file = next((f for f in files if f.endswith(".h5")), None)
            if h5file:
                h5file = results_dir + h5file
                atom_labels, xyz = self.from_h5(h5file)
                all_geoms.append(xyz)
            elif os.path.isfile(results_dir + "dyn.out"):
                dynfile = results_dir + "dyn.out"
                atom_labels, xyz = self.from_dyn(dynfile)
                all_geoms.append(xyz)
            elif os.path.isfile(results_dir + "dyn.xyz"):
                xyzfile = results_dir + "dyn.xyz"
                atom_labels, xyz = self.from_xyz(xyzfile)
                all_geoms.append(xyz)
            else:
                print("\nFile dyn.out or dyn.xyz not available.")
                print("Check the directory %s" % trj + "/RESULTS" + "\n")

        self.xyz = np.concatenate(all_geoms, axis=0)
        self.labels = atom_labels

    def read_eq_geom(self):
        """Read the XYZ coordinates of the reference geometry (geom.xyz),
        and store the values in the class variable ``eq_xyz``.

        """
        try:
            atom_labels, ref_geom = self.from_xyz("geom.xyz")
            self.eq_xyz = np.squeeze(ref_geom, axis=0)
            self.labels = atom_labels
        except FileNotFoundError:
            print("\n-----------------------------------------------------------")
            print("Reference geometry not found!")
            print("The reference geometry is required to compute the RMSD. ")
            print("Check if the geom.xyz file is available in the current dir.")
            print("-----------------------------------------------------------\n")

    @property
    def align_geoms(self):
        """Align the current loaded geometry with respect to the reference geometry
        using the Kabsch algorithm, and computes the corresponding (optimal) RMSD.

        """

        if self.eq_xyz is None:
            self.read_eq_geom()

        self.eq_xyz -= rmsd.centroid(self.eq_xyz)

        if self.xyz is not None:
            xyz_dim = self.xyz.shape
            aligned_geoms = np.empty(xyz_dim, dtype=np.float64)
            rmsd_values = np.empty((xyz_dim[0]), dtype=np.float64)
        else:
            error_msg = "XYZ coordinates not loaded!" + "\n "
            error_msg += "Please make sure that the read_all_trajs function "
            error_msg += "has been executed."
            print(error_msg)
            return

        for idx, geom in enumerate(self.xyz):
            geom -= rmsd.centroid(geom)
            U = rmsd.kabsch(geom, self.eq_xyz)
            geom = np.dot(geom, U)
            geom_rmsd = rmsd.rmsd(self.eq_xyz, geom)
            aligned_geoms[idx] = geom
            rmsd_values[idx] = geom_rmsd

        self.xyz = aligned_geoms
        self.rmsd = rmsd_values


