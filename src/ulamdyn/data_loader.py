class GetCouplings:
    """Class used to read the Nonadiabatic Coupling Vectors (NAC) from the MD trajectories.

    This class does not require arguments in its constructor. The outputs generate by
    the class is given in atomic units.

    Data attributes:
    ----------------
       ``trajectories`` (list): trajectories ID (TRAJXX) available in the working directory.\n
       ``all_nacs`` (dict): store the NAC matrices (per state) for all MD trajectories.\n
       ``dataset`` (dict): dictionary of dataframes with the flattened gradient matrices.
    """

    # Define slots to optimize RAM memory access
    __slots__ = ["trajectories", "all_nacs", "datasets"]

    def __str__(self) -> str:
        """Provide a string representation of the class.

        :return: Short description of the class functionality.
        :rtype: str
        """
        return "Data loader object for nonadiabatic couplings."

    def __init__(self):
        """Class initializer."""
        # This variable contains a list of all available trajectories:
        # [TRAJ1, TRAJ2,..., TRAJN]
        self.trajectories = check_nx_trajs()
        # Store the NAC matrices per state as a dictionary, where
        # the key is an state pair ID (e.g., {'S2S1': np.array})
        self.all_nacs = dict()
        self.datasets = dict()

    @staticmethod
    def from_h5(outfile) -> dict:
        """Read NACs from one trajectory generated by the new Newton-X.

        :param outfile: name of the NX output file in the .h5 format, usually dyn.h5.
        :type outfile: str
        :return: stacked nonadiabatic coupling vectors (NAC) for all steps of a single MD
                 trajectory, provided as a dictionary of tensors (numpy.ndarray, one for
                 each state) with shape (n_steps, n_atoms, 3).
        :rtype: dict
        """
        nacs_dict = dict()
        data = h5py.File(outfile, "r")
        if "nad" in data["particles/all"].keys():
            path_to_grads = "particles/all/nad/value"
        else:
            print("NACs not available!")
            print("Check the NX outputs.")
            return

        nacs = np.array(data[path_to_grads], dtype=np.float64)
        num_blocks = nacs.shape[-1]
        if num_blocks == 1:
            num_blocks += 1
        states = [
            "S" + str(j + 1) + "S" + str(i + 1)
            for i, j in combinations(range(num_blocks), 2)
        ]

        for state in range(states):
            nacs_dict[state] = nacs[:, :, :, state]

        return nacs_dict

    @staticmethod
    def from_nxlog(outfile, tmax=100000) -> dict:
        """Read NACs from one trajectory generated by the classical Newton-X."""
        read_nacs = False
        count_start = 0

        nacs_dict = dict()

        with open(outfile, "r") as nx_log:
            for line in nx_log:

                if "STARTING MOLECULAR DYNAMICS" in line:
                    count_start += 1

                if "STEP" in line:
                    line_list = line.replace(",", "").split()
                    t_current = np.float(line_list[4])
                    if t_current == tmax:
                        break

                if "Nat" in line:
                    num_atoms = np.int(line.split()[-1])

                if "nstat " in line:
                    num_states = np.int(line.split()[-1])
                    num_blocks = np.int(num_states * (num_states - 1) / 2)
                    if num_blocks == 1:
                        num_blocks += 1
                    states = [
                        "S" + str(j + 1) + "S" + str(i + 1)
                        for i, j in combinations(range(num_blocks), 2)
                    ]

                if "phase adjustment" in line:

                    if count_start == 2:
                        read_nacs = False
                        count_start -= 1
                    else:
                        read_nacs = True
                        count_line = 0
                        nacs_step = np.full((num_atoms * num_blocks, 3), np.nan)
                        continue

                if read_nacs:
                    vals = line.split()
                    if len(vals) == 3:
                        atom_nac = np.array(vals, dtype=np.float64)
                        nacs_step[count_line] = atom_nac
                        count_line += 1
                    else:
                        nacs_step = nacs_step.reshape(num_blocks, num_atoms, 3)
                        for i, s in enumerate(states):
                            if s not in nacs_dict.keys():
                                nacs_dict[s] = list()
                            nacs_dict[s].append(nacs_step[i])
                        read_nacs = False

        for k in nacs_dict.keys():
            nacs_dict[k] = np.array(nacs_dict[k])
            nacs_dict[k] = nacs_dict[k].reshape(-1, num_atoms, 3)

        return nacs_dict

    def read_all_trajs(self) -> None:
        """Read NACs from all MD trajectories and store into a dictionary."""
        all_nacs = dict()
        for trj in self.trajectories:
            print("Reading nonadiabatic couplings from %s" % trj + "...")
            tmax = self.trajectories.get(trj)
